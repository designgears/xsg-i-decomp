#!/usr/bin/env python3
"""Compile the game's runs of VU0 macro ops to SSE functions (host build).

The translated COP2 blocks (src/**.c, PORT_HOST side) are sequences of
vu0_arith / vu0_move / vu0_mr32 calls with constant operands.  Called one by
one they keep every register in memory and pay a call per instruction.  This
script finds each run of two or more such calls, gives each distinct run an
SSE function that holds the registers in xmm registers and writes back only
what the run changes (and the final MAC / status), and rewrites the source
with the run replaced by one call.  Same results, bit for bit, as the calls it
replaces: [debug] vu0_runs_check = 1 runs both and logs any difference.

  vu0_runs.py rewrite SRC OUT   copy SRC to OUT with its runs replaced (lines kept)
  vu0_runs.py runs OUT SRC...   OUT: the run functions of all SRCs
  vu0_runs.py scan SRC...       print the files that have runs
"""
import hashlib
import re
import sys

OP = re.compile(r'^(\s*)vu0_(arith|move|mr32)\(([^;()]*)\);\s*$')
ARITH = {'VU0_ADD': 'add', 'VU0_SUB': 'sub', 'VU0_MUL': 'mul', 'VU0_MADD': 'madd', 'VU0_MSUB': 'msub',
         'VU0_MAX': 'max', 'VU0_MINI': 'mini'}


def val(tok):
    tok = tok.strip()
    if tok in ('VU0_ACC', 'VU0_VEC'):
        return -1
    if tok == 'VU0_BQ':
        return 4
    if tok == 'VU0_BI':
        return 5
    return int(tok, 0)


def parse(line):
    m = OP.match(line)
    if not m:
        return None
    kind, args = m.group(2), [a.strip() for a in m.group(3).split(',')]
    try:
        if kind == 'arith':
            if len(args) != 6 or args[0] not in ARITH:
                return None
            return ('arith', args[0], val(args[1]), val(args[2]), val(args[3]), val(args[4]), val(args[5]))
        if len(args) != 3:
            return None
        return (kind, val(args[0]), val(args[1]), val(args[2]))
    except ValueError:
        return None


def safe_start(lines, first):
    """The run starts a statement of its own: not the body of a brace-less if/else/for/while."""
    for j in range(first - 1, -1, -1):
        t = lines[j].strip()
        if not t or t.startswith('#') or t.startswith('//') or t.endswith('*/'):
            continue
        return t.endswith(';') or t.endswith('{') or t.endswith('}')
    return True


def runs_of(text):
    """[(first line index, [ops], [lines])] for runs of >= 2 ops."""
    lines = text.split('\n')
    out, cur = [], []
    for i, l in enumerate(lines + ['']):
        op = parse(l) if i < len(lines) else None
        if op:
            cur.append((i, op))
            continue
        if len(cur) >= 2 and safe_start(lines, cur[0][0]):
            out.append((cur[0][0], [o for _, o in cur]))
        cur = []
    return lines, out


def run_id(ops):
    return hashlib.sha1(repr(ops).encode()).hexdigest()[:12]


def rewrite(src, out):
    text = open(src, encoding='utf-8', errors='surrogateescape').read()
    lines, runs = runs_of(text)
    decls = []
    for first, ops in runs:
        rid = run_id(ops)
        indent = re.match(r'\s*', lines[first]).group(0)
        lines[first] = f'{indent}xsg_vu0_run_{rid}();'
        for k in range(1, len(ops)):
            lines[first + k] = ''   # keep the line numbers
        decls.append(f'void xsg_vu0_run_{rid}(void);')
    head = '/* generated by port/scripts/vu0_runs.py from %s */\n' % src
    head += '\n'.join(sorted(set(decls))) + '\n'
    head += '#line 1 "%s"\n' % src
    with open(out, 'w', encoding='utf-8', errors='surrogateescape') as f:
        f.write(head + '\n'.join(lines))


def lanes(dest):   # PS2 dest (x = bit 3) -> lane mask (lane l = bit l)
    return ((dest >> 3) & 1) | ((dest >> 1) & 2) | ((dest << 1) & 4) | ((dest << 3) & 8)


def keep_mask(ln):   # _mm_set_epi32 order w z y x: -1 keeps the old lane
    return ', '.join('0' if ln & (1 << l) else '-1' for l in (3, 2, 1, 0))


def gen_run(ops):
    rid = run_id(ops)
    used, written = set(), set()
    for o in ops:
        if o[0] == 'arith':
            _, _, dest, fd, fs, ft, bc = o
            used.add(fs)
            if bc != 5 and bc != 4:
                used.add(ft)
            if o[1] in ('VU0_MADD', 'VU0_MSUB'):
                used.add(-1)
            if fd != 0:
                used.add(fd); written.add(fd)
        else:
            _, dest, ft, fs = o
            used.add(fs)
            if ft != 0:
                used.add(ft); written.add(ft)
    name = lambda r: 'acc' if r == -1 else f'r{r}'
    b = [f'void xsg_vu0_run_{rid}(void)', '{']
    if any(o[0] == 'arith' and o[1] not in ('VU0_MAX', 'VU0_MINI') for o in ops):
        b.append('    unsigned orst = 0, st = 0, mac = 0;')
    for r in sorted(used):
        if r == 0:
            b.append('    const __m128i r0 = _mm_setr_epi32(0, 0, 0, 0x3f800000);')
        elif r == -1:
            b.append('    __m128i acc = _mm_loadu_si128((const __m128i *)V.acc.u);')
        else:
            b.append(f'    __m128i r{r} = _mm_loadu_si128((const __m128i *)V.vf[{r}].u);')
    flag_ops = [i for i, o in enumerate(ops) if o[0] == 'arith' and o[1] not in ('VU0_MAX', 'VU0_MINI')]
    last_flag = flag_ops[-1] if flag_ops else -1
    for i, o in enumerate(ops):
        b.append('    {')
        if o[0] == 'arith':
            _, op, dest, fd, fs, ft, bc = o
            ln = lanes(dest)
            b.append(f'        const __m128 x = xsg_vu0_in({name(fs)});')
            if bc == -1:
                b.append(f'        const __m128 y = xsg_vu0_in({name(ft)});')
            elif bc == 4:
                b.append('        const __m128 y = xsg_vu0_in(_mm_set1_epi32((int)V.Q));')
            elif bc == 5:
                b.append('        const __m128 y = xsg_vu0_in(_mm_set1_epi32((int)V.I));')
            else:
                b.append(f'        const __m128 y = xsg_vu0_in(_mm_shuffle_epi32({name(ft)}, {bc * 0x55}));')
            if op in ('VU0_MADD', 'VU0_MSUB'):
                f = '_mm_add_ps' if op == 'VU0_MADD' else '_mm_sub_ps'
                b.append('        const __m128 m = _mm_castsi128_ps(xsg_vu0_out(_mm_mul_ps(x, y), 0, 0, 0, 0));')
                b.append(f'        const __m128 z = {f}(xsg_vu0_in(acc), m);')
            else:
                f = {'VU0_ADD': '_mm_add_ps', 'VU0_SUB': '_mm_sub_ps', 'VU0_MUL': '_mm_mul_ps',
                     'VU0_MAX': '_mm_max_ps', 'VU0_MINI': '_mm_min_ps'}[op]
                b.append(f'        const __m128 z = {f}(x, y);')
            if op in ('VU0_MAX', 'VU0_MINI'):
                b.append('        const __m128i r = xsg_vu0_out(z, 0, 0, 0, 0);')
            else:
                b.append('        int ov, un, zr, sg;')
                b.append('        const __m128i r = xsg_vu0_out(z, &ov, &un, &zr, &sg);')
                b.append(f'        st = ((zr & {ln}) ? 1u : 0u) | ((sg & {ln}) ? 2u : 0u) | ((un & {ln}) ? 4u : 0u) | ((ov & {ln}) ? 8u : 0u);')
                b.append('        orst |= st;')
                if i == last_flag:
                    b.append(f'        mac = xsg_vu0_rev4((unsigned)zr & {ln}) | xsg_vu0_rev4((unsigned)sg & {ln}) << 4 |')
                    b.append(f'              xsg_vu0_rev4((unsigned)un & {ln}) << 8 | xsg_vu0_rev4((unsigned)ov & {ln}) << 12;')
            if fd != 0:
                d = name(fd)
                if ln == 15:
                    b.append(f'        {d} = r;')
                else:
                    b.append(f'        {d} = xsg_vu0_sel(_mm_set_epi32({keep_mask(ln)}), {d}, r);')
        else:
            kind, dest, ft, fs = o
            ln = lanes(dest)
            src = name(fs) if kind == 'move' else f'_mm_shuffle_epi32({name(fs)}, _MM_SHUFFLE(0, 3, 2, 1))'
            if ft != 0:
                d = name(ft)
                if ln == 15:
                    b.append(f'        {d} = {src};')
                else:
                    b.append(f'        {d} = xsg_vu0_sel(_mm_set_epi32({keep_mask(ln)}), {d}, {src});')
        b.append('    }')
    for r in sorted(written):
        if r == -1:
            b.append('    _mm_storeu_si128((__m128i *)V.acc.u, acc);')
        else:
            b.append(f'    _mm_storeu_si128((__m128i *)V.vf[{r}].u, r{r});')
    if flag_ops:
        b.append('    V.mac = mac;')
        b.append('    V.status = (V.status & 0xff0u) | (orst << 6) | st;')
    b.append('}')
    # the reference: the calls it replaces, for [debug] vu0_runs_check
    r = [f'static void ref_{rid}(void)', '{']
    for o in ops:
        if o[0] == 'arith':
            _, op, dest, fd, fs, ft, bc = o
            r.append(f'    vu0_arith({op}, {dest}, {fd}, {fs}, {ft}, {bc});')
        else:
            r.append(f'    vu0_{o[0]}({o[1]}, {o[2]}, {o[3]});')
    r.append('}')
    return rid, '\n'.join(r), '\n'.join(b)


def gen_runs(out, srcs):
    seen = {}
    for s in srcs:
        _, runs = runs_of(open(s, encoding='utf-8', errors='surrogateescape').read())
        for _, ops in runs:
            seen.setdefault(run_id(ops), ops)
    parts = ['/* generated by port/scripts/vu0_runs.py: %d VU0 op runs as SSE */' % len(seen),
             '#define XSG_VU0_NO_INLINE', '#include "vu0.h"', '#include "vu0_inline.h"', '#include <string.h>',
             '#include <stdlib.h>', '#include "xsg_rt.h"', '#include "xsg_settings.h"', '#define V xsg_vu0', '',
             'static int check = -1;',
             'static void check_run(void (*fast)(void), void (*ref)(void), const char *id)',
             '{',
             '    static unsigned long long n, bad;',
             '    const XsgVu0 in = V;',
             '    fast();',
             '    const XsgVu0 f = V;',
             '    V = in;',
             '    ref();',
             '    n++;',
             '    if (memcmp(&f, &V, sizeof f) && bad++ < 20) xsg_logf("[vu0] run %s differs from its ops\\n", id);',
             '    if (n % 1000000 == 0) xsg_logf("[vu0] op runs checked: %llu, %llu differ\\n", n, bad);',
             '}', '']
    for rid in sorted(seen):
        _, ref, fast = gen_run(seen[rid])
        parts.append(ref)
        parts.append(fast.replace(f'void xsg_vu0_run_{rid}(void)\n{{',
                                  f'static void fast_{rid}(void);\nvoid xsg_vu0_run_{rid}(void)\n{{\n'
                                  f'    if (check < 0) check = xsg_cfg("debug.vu0_runs_check") && atoi(xsg_cfg("debug.vu0_runs_check"));\n'
                                  f'    if (check) {{ check_run(fast_{rid}, ref_{rid}, "{rid}"); return; }}\n'
                                  f'    fast_{rid}();\n}}\nstatic void fast_{rid}(void)\n{{', 1))
        parts.append('')
    open(out, 'w').write('\n'.join(parts) + '\n')


def main():
    cmd = sys.argv[1]
    if cmd == 'rewrite':
        rewrite(sys.argv[2], sys.argv[3])
    elif cmd == 'runs':
        gen_runs(sys.argv[2], sys.argv[3:])
    elif cmd == 'scan':
        for s in sys.argv[2:]:
            if runs_of(open(s, encoding='utf-8', errors='surrogateescape').read())[1]:
                print(s)


if __name__ == '__main__':
    main()
