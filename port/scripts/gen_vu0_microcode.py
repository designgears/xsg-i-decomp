#!/usr/bin/env python3
"""Emit the resident VU0 microprogram (Vu0MicroCode.dvp) as a C array.

Reads the DVP-assembled object of the PS2 build (build/main/build/vu0/
Vu0MicroCode.o) and takes the MPG payload of its .vudata packet: the VU0 instruction-memory
image (224 pairs, 0x700 bytes) the game DMAs to VU0 at start-up.

Usage: gen_vu0_microcode.py <Vu0MicroCode.o> <out.c>
"""
import struct
import sys


def main():
    obj, out = sys.argv[1], sys.argv[2]
    d = open(obj, "rb").read()
    shoff, = struct.unpack_from("<I", d, 0x20)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", d, 0x2E)
    secs = [struct.unpack_from("<IIIIIIIIII", d, shoff + i * shentsize) for i in range(shnum)]
    strtab = secs[shstrndx]
    img = None
    for s in secs:
        name = d[strtab[4] + s[0]:].split(b"\0")[0]
        if name == b".vudata":
            v = d[s[4]:s[4] + s[5]]
            # size header qword, then DMAcnt tag + VIF NOP + MPG(num, addr 0)
            tag, nop, mpg = struct.unpack_from("<QII", v, 16)
            num = (mpg >> 16) & 0xFF or 256
            if mpg >> 24 != 0x4A or mpg & 0xFFFF:
                sys.exit("gen_vu0_microcode: unexpected VIF code %08x" % mpg)
            img = v[32:32 + num * 8]
    if img is None:
        sys.exit("gen_vu0_microcode: no .vudata section in " + obj)
    with open(out, "w") as f:
        f.write("/* generated by port/scripts/gen_vu0_microcode.py -- do not edit */\n")
        f.write("const unsigned char xsg_vu0_microcode[%d] __attribute__((aligned(16))) = {\n" % len(img))
        for i in range(0, len(img), 16):
            f.write("  " + ",".join("0x%02x" % b for b in img[i:i + 16]) + ",\n")
        f.write("};\nconst unsigned int xsg_vu0_microcode_size = %d;\n" % len(img))


if __name__ == "__main__":
    main()
